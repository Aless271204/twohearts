"""Validate the editorial catalog and generate its compile-time Dart data.

Run with --check in CI. --source-dir optionally checks the exact cached source
files recorded during editorial review; it does not contact a network service.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parents[1]


def normalized(text):
    # Ignore verse capitalization, punctuation, line breaks, and only the
    # obsolete accents on single-letter prepositions/conjunctions.
    text = re.sub(r"\b[áéóÁÉÓ]\b", lambda m: {
        "á": "a", "é": "e", "ó": "o", "Á": "A", "É": "E", "Ó": "O",
    }[m[0]], text)
    return "".join(c for c in unicodedata.normalize("NFC", text).casefold()
                   if c.isalnum())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source-dir", type=Path)
    args = parser.parse_args()
    rows = json.loads((ROOT / "data/quotes/literary.es.json").read_text("utf-8"))
    sources = {s["id"]: s for s in json.loads(
        (ROOT / "data/quotes/sources.json").read_text("utf-8"))}
    ids, texts = set(), set()
    required = {"id", "category", "author", "work", "text", "url", "source",
                "language", "edition", "verified_at", "text_policy"}
    for row in rows:
        assert required <= row.keys(), row
        assert all(isinstance(v, str) and v.strip() for v in row.values()), row
        assert row["id"] not in ids, row["id"]
        assert normalized(row["text"]) not in texts, row["id"]
        ids.add(row["id"])
        texts.add(normalized(row["text"]))
        assert row["category"] == "literature" and row["language"] == "es"
        assert row["source"] == f'{row["author"]} · {row["work"]}'
        assert row["url"].startswith("https://")
        assert row["edition"] in sources
        if args.source_dir:
            source = sources[row["edition"]]
            raw = (args.source_dir / source["local_file"]).read_bytes()
            assert hashlib.sha256(raw).hexdigest() == source["sha256"], source
            text = raw.decode("utf-8-sig").replace("\r\n", "\n")
            if row["author"] == "Gustavo Adolfo Bécquer":
                # Check the numbered poem, not merely any passage in the book.
                text = text[text.rfind("\nRIMAS"):]
                number = row["work"].removeprefix("Rima ")
                text = re.split(r"\n" + number + r"\n", text)[1]
                text = re.split(r"\n[IVXLCDM]+\n", text)[0]
            assert normalized(row["text"]) in normalized(text), row["id"]
    lines = ["// GENERATED by scripts/generate_literary_quotes.py. Do not edit.",
             "// dart format off", "const literaryQuoteCatalog = <Map<String, String>>["]
    for row in rows:
        lines.append("  {")
        for key, value in row.items():
            literal = json.dumps(value, ensure_ascii=False).replace("$", r"\$")
            lines.append(f"    '{key}': {literal},")
        lines.append("  },")
    lines += ["];", "// dart format on", ""]
    output = "\n".join(lines)
    target = ROOT / "lib/core/literary_quotes.g.dart"
    if args.check:
        assert target.read_text("utf-8") == output, "Generated Dart catalog is stale"
    else:
        target.write_text(output, encoding="utf-8")
    print(f"Validated {len(rows)} literary quotes / "
          f"{len({r['author'] for r in rows})} authors")


if __name__ == "__main__":
    main()
